function translateDynamic(value: string) {
  const rules: Array<[RegExp, (...parts: string[]) => string]> = [
    [/^(\d+) customers?$/, (count) => `${count} 位顾客`],
    [/^(\d+) pets?$/, (count) => `${count} 只宠物`],
    [/^(\d+) orders?$/, (count) => `${count} 笔订单`],
    [/^(\d+) records?$/, (count) => `${count} 笔记录`],
    [/^(\d+) events?$/, (count) => `${count} 项记录`],
    [/^(\d+) confirmed$/, (count) => `${count} 笔已确认`],
    [/^Record (RM\d+) Balance$/, (amount) => `记录 ${amount} 余额付款`],
    [/^Check-in opens (.+)$/, (date) => `${date} 起可办理入住`],
    [/^Care records for (.+)$/, (name) => `${name} 的照顾记录`],
    [/^Add a pet for (.+)$/, (name) => `为 ${name} 新增宠物`],
    [/^Joined (.+)$/, (date) => `加入于 ${date}`],
    [/^(\d+) current orders$/, (count) => `${count} 笔当前订单`],
    [/^(RM\d+) due$/, (amount) => `待收 ${amount}`]
  ];
  for (const [pattern, format] of rules) {
    const match = value.match(pattern);
    if (match) return format(...match.slice(1));
  }
  return ZH[value] || value;
}

const originals = new WeakMap<Node, string>();
const applied = new WeakMap<Node, string>();
const originalAttributes = new WeakMap<Element, Map<string, string>>();
const appliedAttributes = new WeakMap<Element, Map<string, string>>();
const TRANSLATED_ATTRIBUTES = ["placeholder", "title", "aria-label"] as const;

function translatedWithWhitespace(value: string) {
  const leading = value.match(/^\s*/)?.[0] || "";
  const trailing = value.match(/\s*$/)?.[0] || "";
  const end = trailing.length ? value.length - trailing.length : value.length;
  const core = value.slice(leading.length, end);
  return `${leading}${translateDynamic(core)}${trailing}`;
}

function localizeNode(node: Node, language: HostUiLanguage) {
  if (node.nodeType === Node.TEXT_NODE) {
    const current = node.nodeValue || "";
    if (!current.trim()) return;
    if (!originals.has(node) || (applied.has(node) && current !== applied.get(node))) originals.set(node, current);
    const original = originals.get(node) || current;
    const next = language === "zh" ? translatedWithWhitespace(original) : original;
    if (current !== next) node.nodeValue = next;
    applied.set(node, next);
    return;
  }
  if (!(node instanceof Element) || ["SCRIPT", "STYLE", "TEXTAREA"].includes(node.tagName)) return;
  let attributeOriginals = originalAttributes.get(node);
  let attributeApplied = appliedAttributes.get(node);
  if (!attributeOriginals) {
    attributeOriginals = new Map();
    originalAttributes.set(node, attributeOriginals);
  }
  if (!attributeApplied) {
    attributeApplied = new Map();
    appliedAttributes.set(node, attributeApplied);
  }
  for (const attribute of TRANSLATED_ATTRIBUTES) {
    const current = node.getAttribute(attribute);
    if (!current) continue;
    if (!attributeOriginals.has(attribute) || (attributeApplied.has(attribute) && current !== attributeApplied.get(attribute))) {
      attributeOriginals.set(attribute, current);
    }
    const original = attributeOriginals.get(attribute) || current;
    const next = language === "zh" ? translateDynamic(original) : original;
    if (current !== next) node.setAttribute(attribute, next);
    attributeApplied.set(attribute, next);
  }
  node.childNodes.forEach((child) => localizeNode(child, language));
}

export function HostLanguageRuntime({ language }: { language: HostUiLanguage }) {
  useLayoutEffect(() => {
    const root = document.body;
    let translating = false;
    const apply = () => {
      if (translating) return;
      translating = true;
      localizeNode(root, language);
      translating = false;
    };
    apply();
    const observer = new MutationObserver(() => queueMicrotask(apply));
    observer.observe(root, { subtree: true, childList: true, characterData: true, attributes: true, attributeFilter: [...TRANSLATED_ATTRIBUTES] });
    return () => observer.disconnect();
  }, [language]);
  return null;
}
